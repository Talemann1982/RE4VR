int REFramework::add_font(const std::filesystem::path& filepath, int size, const std::vector<ImWchar>& ranges) {
    // Look for a font already matching this description.
    for (int i = 0; i < m_additional_fonts.size(); ++i) {
        const auto& font = m_additional_fonts[i];

        if (font.filepath == filepath && font.size == size && font.ranges == ranges) {
            return i;
        }
    }

    m_additional_fonts.emplace_back(REFramework::AdditionalFont{filepath, size, ranges, (ImFont*)nullptr});
    m_fonts_need_updating = true;

    return m_additional_fonts.size() - 1;
}

void REFramework::update_fonts() {
    if (!m_fonts_need_updating) {
        return;
    }

    m_fonts_need_updating = false;

    auto& fonts = ImGui::GetIO().Fonts;
    fonts->Clear();
    m_heading_font = nullptr;   // der alte Zeiger zeigt nach Clear() ins Leere
    m_vr_font_base = nullptr;
    m_vr_font_heading = nullptr;
    m_vr_font_nav = nullptr;

    // using 'reframework_pictographic.mode' file to 
    // replace '?' to most flag in WorldObjectsViewer
    ImFontConfig custom_icons{}; 
    custom_icons.FontDataOwnedByAtlas = false;

    const ImWchar cjk_ranges[] = {
        0x0020, 0x00FF, // Basic Latin + Latin Supplement
        0x2000, 0x206F, // General Punctuation
        0x3000, 0x30FF, // CJK Symbols and Punctuations, Hiragana, Katakana
        0x3131, 0x3163, // Korean alphabets
        0x31F0, 0x31FF, // Katakana Phonetic Extensions
        0xAC00, 0xD7A3, // Korean characters
        0xFF00, 0xFFEF, // Half-width characters
        0xFFFD, 0xFFFD, // Invalid
        0x4e00, 0x9FAF, // CJK Ideograms,
        0
    };

    // [BARLOW 11.09.2026] Grundschrift ist Barlow Condensed SemiBold (OFL, vorher
    // Big Shoulders SemiBold) -- nur Latin, die hat sie vollstaendig.
    // Das Array ist statisch, darf dem Atlas also NICHT gehoeren.
    static const ImWchar latin_ranges[] = {0x0020, 0x00FF, 0};

    ImFontConfig base_cfg{};
    base_cfg.FontDataOwnedByAtlas = false;
    fonts->AddFontFromMemoryTTF((void*)barlow_condensed_semibold_ttf, (int)sizeof(barlow_condensed_semibold_ttf),
        (float)m_font_size, &base_cfg, latin_ranges);

    // Roboto CJK darunter EINGEMISCHT: alles, was Barlow nicht hat
    // (chinesisch/japanisch/koreanisch, Sonderzeichen), kommt weiter von dort --
    // sonst stuenden in den REFramework-Fenstern Fragezeichen. Zeichen, die
    // Barlow schon hat, ueberschreibt ImGui beim Mischen nicht.
    ImFontConfig cjk_cfg{};
    cjk_cfg.MergeMode = true;
    fonts->AddFontFromMemoryCompressedTTF((void*)RobotoCJKSC_Medium_compressed_data, RobotoCJKSC_Medium_compressed_size,
        (float)m_font_size, &cjk_cfg, cjk_ranges);

    // https://fontawesome.com/
    custom_icons.PixelSnapH = true;
    custom_icons.MergeMode = true;
    custom_icons.FontDataOwnedByAtlas = false;
    static const ImWchar icon_ranges[] = {0xF000, 0xF976, 0}; // ICON_MIN_FA ICON_MAX_FA
    fonts->AddFontFromMemoryTTF((void*)af_faprolight_ptr, af_faprolight_size, (float)m_font_size, &custom_icons, icon_ranges);

    // [UEBERSCHRIFTEN 11.09.2026] re4-title ("Resident Evil 4 Remake Font"),
    // HEADING_FONT_EXTRA px groesser als die Grundschrift. Echt in dieser Groesse
    // gerastert statt per SetWindowFontScale hochgezogen -- das waere unscharf.
    // Nur Latin, damit der Atlas klein bleibt. Steht HINTER der Grundschrift,
    // die bleibt also Standardschrift (erster Eintrag).
    static const ImWchar heading_ranges[] = {0x0020, 0x00FF, 0};

    ImFontConfig heading_cfg{};
    heading_cfg.FontDataOwnedByAtlas = false;
    m_heading_font = fonts->AddFontFromMemoryTTF((void*)re4_title_ttf, (int)sizeof(re4_title_ttf),
        (float)(m_font_size + HEADING_FONT_EXTRA), &heading_cfg, heading_ranges);

    // [VR-SCHRIFT 11.09.2026] Dieselben zwei Schriften fuers VR-Menue noch einmal,
    // VR_FONT_OVERSAMPLE-fach so gross gerastert. Das VR-Menue skaliert sie ueber
    // die Fensterschrift-Skalierung auf die eingestellte Groesse herunter -- das
    // bleibt bis zum Faktor VR_FONT_OVERSAMPLE scharf, statt kleine Glyphen
    // hochzuziehen. Nur Latin + Icons: die riesigen CJK-Bereiche hier nochmal zu
    // rastern wuerde den Atlas sprengen (im VR-Menue erscheinen CJK-Zeichen als ?).
    {
        const auto vr_size = (float)(m_font_size * VR_FONT_OVERSAMPLE);

        ImFontConfig vr_base_cfg{};
        vr_base_cfg.FontDataOwnedByAtlas = false;
        m_vr_font_base = fonts->AddFontFromMemoryTTF((void*)barlow_condensed_semibold_ttf, (int)sizeof(barlow_condensed_semibold_ttf),
            vr_size, &vr_base_cfg, latin_ranges);

        ImFontConfig vr_icon_cfg{};
        vr_icon_cfg.MergeMode = true;
        vr_icon_cfg.PixelSnapH = true;
        vr_icon_cfg.FontDataOwnedByAtlas = false;
        fonts->AddFontFromMemoryTTF((void*)af_faprolight_ptr, af_faprolight_size, vr_size, &vr_icon_cfg, icon_ranges);

        ImFontConfig vr_heading_cfg{};
        vr_heading_cfg.FontDataOwnedByAtlas = false;
        m_vr_font_heading = fonts->AddFontFromMemoryTTF((void*)re4_title_ttf, (int)sizeof(re4_title_ttf),
            (float)((m_font_size + HEADING_FONT_EXTRA) * VR_FONT_OVERSAMPLE), &vr_heading_cfg, heading_ranges);

        // [KATEGORIE-SCHRIFT 11.09.2026] Kategorien links wieder in re4-title, der
        // Resi-Schrift (zwischendurch Big Shoulders, Anton, Oswald). Exakt Schrift und
        // Groesse der Ueberschriften -- deshalb dieselbe Atlas-Schrift statt einer Kopie.
        m_vr_font_nav = m_vr_font_heading;
    }

    for (auto& font : m_additional_fonts) {
        const ImWchar* ranges = nullptr;

        if (!font.ranges.empty()) {
            ranges = font.ranges.data();
        }

        if (fs::exists(font.filepath)) {
            font.font = fonts->AddFontFromFileTTF(font.filepath.string().c_str(), (float)font.size, nullptr, ranges);
        } else {
            if (ranges == nullptr) {
                ranges = cjk_ranges;
            }
            font.font = fonts->AddFontFromMemoryCompressedTTF((void*)RobotoCJKSC_Medium_compressed_data, RobotoCJKSC_Medium_compressed_size, (float)font.size, nullptr, ranges);
        }
    }

    fonts->Build();
    m_wants_device_object_cleanup = true;
}

