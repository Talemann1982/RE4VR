// (hinter dem ganzen Menue).
void REFramework::create_menu_images_d3d12(ID3D12Device* device) {
    m_d3d12.bindings_image = load_embedded_image_d3d12(device, re4vr_bindings_jpg, sizeof(re4vr_bindings_jpg),
        D3D12::SRV::RE4VR_BINDINGS_IMAGE, L"Framework::m_d3d12.bindings_image");
    m_d3d12.menu_background = load_embedded_image_d3d12(device, re4vr_menu_background_png, sizeof(re4vr_menu_background_png),
        D3D12::SRV::RE4VR_MENU_BACKGROUND, L"Framework::m_d3d12.menu_background");
}

// Eingebettetes Bild (JPG/PNG) per DirectXTK12/WIC in eine Textur laden und ihre
// SRV in den Slot `slot` legen -- derselbe Heap, den beide ImGui-Renderer (Desktop
// und VR) setzen. Leer, wenn das Laden scheitert.
// Rueckgabetyp voll qualifiziert: ComPtr ist nur INNERHALB der Klasse als Kurzname bekannt.
Microsoft::WRL::ComPtr<ID3D12Resource> REFramework::load_embedded_image_d3d12(ID3D12Device* device, const unsigned char* data,
                                                                             size_t size, D3D12::SRV slot, const wchar_t* name) {
    if (device == nullptr) {
        return nullptr;
    }

    // WIC braucht COM auf diesem Thread. Bewusst KEIN CoUninitialize: DirectXTK
    // merkt sich die WIC-Factory statisch, sie muss bei einem spaeteren
    // init_d3d12 (Device-Reset) noch gueltig sein. Ist der Thread schon STA,
    // meldet das RPC_E_CHANGED_MODE -- WIC funktioniert dann trotzdem.
    CoInitializeEx(nullptr, COINIT_MULTITHREADED);

    DirectX::ResourceUploadBatch upload{device};
    upload.Begin();

    ComPtr<ID3D12Resource> texture{};

    // IGNORE_SRGB: das Bild soll so aussehen wie am PC. Eine _SRGB-Textur wuerde
    // beim Lesen linearisiert und im UNORM-Ziel von ImGui zu dunkel landen.
    const auto hr = DirectX::CreateWICTextureFromMemoryEx(device, upload, data, size,
        0, D3D12_RESOURCE_FLAG_NONE, DirectX::WIC_LOADER_IGNORE_SRGB, texture.GetAddressOf());

    auto finished = upload.End(m_d3d12_hook->get_command_queue());
    finished.wait();

    if (FAILED(hr) || texture == nullptr) {
        spdlog::error("[D3D12] Menu image (SRV slot {}): CreateWICTextureFromMemoryEx failed (0x{:08X})", (int)slot, (uint32_t)hr);
        return nullptr;
    }

    texture->SetName(name);
    device->CreateShaderResourceView(texture.Get(), nullptr, m_d3d12.get_cpu_srv(device, slot));

    const auto desc = texture->GetDesc();
    spdlog::info("[D3D12] Menu image (SRV slot {}) loaded: {}x{}, format {}", (int)slot, (uint32_t)desc.Width, (uint32_t)desc.Height, (uint32_t)desc.Format);

    return texture;
}

bool REFramework::draw_menu_background() {
    if (m_renderer_type != RendererType::D3D12 || m_d3d12.menu_background == nullptr || m_d3d12.srv_desc_heap == nullptr) {
        return false;
    }

    auto device = m_d3d12_hook->get_device();

    if (device == nullptr) {
        return false;
    }

    const auto desc = m_d3d12.menu_background->GetDesc();
    const auto display = ImGui::GetIO().DisplaySize;

    if (desc.Width == 0 || desc.Height == 0 || display.x < 1.0f || display.y < 1.0f) {
        return false;
    }

    // Bildfuellend mit festem Seitenverhaeltnis: der Ueberstand wird mittig
    // abgeschnitten statt das Bild zu verzerren. VR (1920x1080) passt genau.
    const float image_aspect = (float)desc.Width / (float)desc.Height;
    const float display_aspect = display.x / display.y;
    ImVec2 uv0{0.0f, 0.0f};
    ImVec2 uv1{1.0f, 1.0f};

    if (display_aspect > image_aspect) {
        const float cut = (1.0f - (image_aspect / display_aspect)) * 0.5f;   // oben und unten
        uv0.y = cut;
        uv1.y = 1.0f - cut;
    } else {
        const float cut = (1.0f - (display_aspect / image_aspect)) * 0.5f;   // links und rechts
        uv0.x = cut;
        uv1.x = 1.0f - cut;
    }

    const auto alpha = (int)(std::clamp(m_vr_menu_background_opacity, 0.0f, 1.0f) * 255.0f + 0.5f);

    ImGui::GetBackgroundDrawList()->AddImage((ImTextureID)m_d3d12.get_gpu_srv(device, D3D12::SRV::RE4VR_MENU_BACKGROUND).ptr,
        ImVec2{0.0f, 0.0f}, display, uv0, uv1, IM_COL32(255, 255, 255, alpha));

    return true;
}

void REFramework::draw_bindings_image() {
    if (m_renderer_type != RendererType::D3D12 || m_d3d12.bindings_image == nullptr || m_d3d12.srv_desc_heap == nullptr) {
        ImGui::TextWrapped("Bindings image not available.");
        return;
    }

    auto device = m_d3d12_hook->get_device();

    if (device == nullptr) {
        return;
    }

    const auto desc = m_d3d12.bindings_image->GetDesc();
    const auto avail = ImGui::GetContentRegionAvail();

    if (avail.x < 1.0f || avail.y < 1.0f || desc.Width == 0 || desc.Height == 0) {
        return;
    }

    const auto tex = (ImTextureID)m_d3d12.get_gpu_srv(device, D3D12::SRV::RE4VR_BINDINGS_IMAGE).ptr;
    const float img_aspect = (float)desc.Width / (float)desc.Height;

    // [QUERFORMAT 16.09.2026 -- Ansage des Users] Das Bild ist jetzt quer (Leon +
    // Ada, 1536x1024) und fuellt die rechte Spalte: so gross, wie Breite UND
    // Hoehe es erlauben, ohne Scrollen, waagerecht mittig. (Bis dahin die
    // vertikale Fassung auf voller Breite, der Bereich scrollte.)
    // Unter jeder Kategorie haengt draw_menu_detail noch eine Zeile Luft an --
    // die geht von der Hoehe ab, sonst entstuende genau dafuer ein Scrollbalken.
    const float max_h = std::max(1.0f, avail.y - ImGui::GetTextLineHeight() - ImGui::GetStyle().ItemSpacing.y * 2.0f);
    float w = avail.x;
    float h = w / img_aspect;

    if (h > max_h) {
        h = max_h;
        w = h * img_aspect;
    }

    ImGui::SetCursorPosX(ImGui::GetCursorPosX() + (avail.x - w) * 0.5f);

    // Das Bild ist ein Knopf: Maus-Klick UND Controller-/Tastatur-Auswahl
    // oeffnen die Vergroesserung.
    const ImVec2 p0 = ImGui::GetCursorScreenPos();
    const ImVec2 p1{p0.x + w, p0.y + h};

    // [NAV 16.09.2026] InvisibleButton ist in ImGui 1.91 ab Werk NoNav -- ohne
    // EnableNav erreicht ihn weder der Controller noch die Tastatur.
    if (ImGui::InvisibleButton("##bindings_image", ImVec2{w, h}, ImGuiButtonFlags_EnableNav)) {
        ImGui::OpenPopup("##bindings_zoom");
    }

    const bool image_focused = ImGui::IsItemFocused();

    auto* const dl = ImGui::GetWindowDrawList();
    dl->AddImage(tex, p0, p1);

    // [ZOOM-HINWEIS 16.09.2026 -- Ansage des Users] Unten mittig UEBER dem Bild,
    // auf einer halbdurchsichtigen dunklen Flaeche, damit er auf jedem Hintergrund
    // lesbar bleibt.
    {
        static const char* const HINT = "Click to zoom";
        const ImVec2 ts = ImGui::CalcTextSize(HINT);
        const float pad_x = ts.y * 0.6f;
        const float pad_y = ts.y * 0.25f;
        const float margin = ts.y * 0.6f;
        const ImVec2 t0{(p0.x + p1.x - ts.x) * 0.5f, p1.y - margin - pad_y - ts.y};
        const ImVec2 r0{t0.x - pad_x, t0.y - pad_y};
        const ImVec2 r1{t0.x + ts.x + pad_x, t0.y + ts.y + pad_y};

        // Markiert (Controller/Tastatur): die Flaeche im Menue-Rot.
        const ImU32 bg = image_focused
            ? ImGui::GetColorU32(ImGui::GetStyleColorVec4(ImGuiCol_SliderGrab))
            : IM_COL32(0, 0, 0, 170);

        dl->AddRectFilled(r0, r1, bg, ts.y * 0.3f);
        dl->AddText(t0, IM_COL32(255, 255, 255, 235), HINT);
    }

    // [ZOOM 16.09.2026] Vergroesserung: ein Popup ueber das ganze Menue, das Bild
    // so gross wie moeglich. Klick (bzw. Auswahl) schliesst es wieder; "zurueck"
    // (Controller/Backspace) und ein Klick daneben ebenso -- das erledigt ImGui fuer
    // Popups selbst.
    const auto* const vp = ImGui::GetMainViewport();

    ImGui::SetNextWindowPos(vp->Pos, ImGuiCond_Always);
    ImGui::SetNextWindowSize(vp->Size, ImGuiCond_Always);
    ImGui::SetNextWindowBgAlpha(0.94f);
    ImGui::PushStyleVar(ImGuiStyleVar_WindowPadding, ImVec2{0.0f, 0.0f});
    ImGui::PushStyleVar(ImGuiStyleVar_PopupRounding, 0.0f);
    ImGui::PushStyleVar(ImGuiStyleVar_PopupBorderSize, 0.0f);

    if (ImGui::BeginPopup("##bindings_zoom", ImGuiWindowFlags_NoDecoration | ImGuiWindowFlags_NoMove
                                                 | ImGuiWindowFlags_NoSavedSettings)) {
        float zw = vp->Size.x;
        float zh = zw / img_aspect;

        if (zh > vp->Size.y) {
            zh = vp->Size.y;
            zw = zh * img_aspect;
        }

        const ImVec2 z0{vp->Pos.x + (vp->Size.x - zw) * 0.5f, vp->Pos.y + (vp->Size.y - zh) * 0.5f};

        ImGui::SetCursorScreenPos(vp->Pos);

        if (ImGui::InvisibleButton("##bindings_zoom_close", vp->Size, ImGuiButtonFlags_EnableNav)) {
            ImGui::CloseCurrentPopup();
        }

        ImGui::GetWindowDrawList()->AddImage(tex, z0, ImVec2{z0.x + zw, z0.y + zh});
        ImGui::EndPopup();
    }

    ImGui::PopStyleVar(3);
}

void REFramework::deinit_d3d12() {
    for (auto& ctx : m_d3d12.cmd_ctxs) {
        if (ctx != nullptr) {
            ctx->reset();
        }
    }

    m_d3d12.cmd_ctxs.clear();

    for (auto userdata : m_d3d12.imgui_backend_datas) {
        if (userdata != nullptr) {
            ImGui::GetIO().BackendRendererUserData = userdata;
            ImGui_ImplDX12_Shutdown();
        }
    }

    ImGui::GetIO().BackendRendererUserData = nullptr;
    m_d3d12 = {};
}
